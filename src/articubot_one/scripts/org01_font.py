def text_width(text, scale=1.0):
    width = 0
    for ch in text:
        width += GLYPH_DATA.get(ch, GLYPH_DATA['?'] if '?' in GLYPH_DATA else GLYPH_DATA[' '])[2]
    return max(0, int(round(width * scale)))


def _draw_text_raw(draw, x, y, text, fill=0):
    baseline = y + 4
    cursor_x = x
    for ch in text:
        width, height, advance, x_off, y_off, rows = GLYPH_DATA.get(
            ch, GLYPH_DATA.get('?', GLYPH_DATA[' '])
        )
        if width and height:
            top = baseline + y_off
            left = cursor_x + x_off
            for row_idx, row in enumerate(rows):
                for col_idx, pixel in enumerate(row):
                    if pixel != '#':
                        continue
                    draw.point((left + col_idx, top + row_idx), fill=fill)
        cursor_x += advance
    return cursor_x - x


def draw_text(draw, x, y, text, fill=0, scale=1.0):
    if scale == 1.0:
        return _draw_text_raw(draw, x, y, text, fill=fill)

    width = max(1, text_width(text))
    height = 9
    base = Image.new('1', (width, height), 1)
    base_draw = ImageDraw.Draw(base)
    _draw_text_raw(base_draw, 0, 0, text, fill=0)
    scaled_w = max(1, int(round(base.width * scale)))
    scaled_h = max(1, int(round(base.height * scale)))
    scaled = base.resize((scaled_w, scaled_h), resample=Image.NEAREST)
    for py in range(scaled_h):
        for px in range(scaled_w):
            if scaled.getpixel((px, py)) == 0:
                draw.point((x + px, y + py), fill=fill)
    return scaled_w
